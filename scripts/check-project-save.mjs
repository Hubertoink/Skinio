import { _electron as electron, expect } from "@playwright/test";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const dir = path.resolve(`artifacts/project-save-${Date.now()}`);
await mkdir(dir, { recursive: true });
const a = path.join(dir, "a.skinforge"), b = path.join(dir, "b.skinforge");
const env = { ...process.env, SKIN_FORGE_TEST_DATA: path.join(dir, "profile") };
delete env.ELECTRON_RUN_AS_NODE;
let app;
const launch = async () => {
  app = await electron.launch({ ...(process.argv[2] ? { executablePath: path.resolve(process.argv[2]), args: [] } : { args: ["."] }), env });
  await app.evaluate(({ dialog }) => {
    global.__saveCount = 0;
    global.__destination = null;
    dialog.showSaveDialog = async () => {
      global.__saveCount++;
      return { canceled: !global.__destination, filePath: global.__destination };
    };
    dialog.showOpenDialog = async () => ({ canceled: !global.__source, filePaths: global.__source ? [global.__source] : [] });
  });
  const page = await app.firstWindow();
  await page.getByLabel("Projektname").waitFor();
  return page;
};
const target = (file) => app.evaluate((_, file) => { global.__destination = file; }, file);
const count = () => app.evaluate(() => global.__saveCount);
const readName = async (file) => JSON.parse(await readFile(file, "utf8")).name;
try {
  let page = await launch();
  const save = () => page.getByRole("button", { name: "Speichern", exact: true }).click();
  const saveAs = () => page.getByRole("button", { name: "Speichern unter", exact: true }).click();
  await page.getByLabel("Projektname").fill("First");
  await target(a);
  await save();
  await expect(page.locator(".save-state")).toContainText("Projektdatei gespeichert");
  expect(await count()).toBe(1);
  expect(await readName(a)).toBe("First");
  await page.getByLabel("Projektname").fill("Changed");
  await expect(page.locator(".save-state")).toContainText("Ungespeicherte Änderungen");
  await expect(page.locator(".save-state")).toContainText("Lokal gesichert");
  await page.getByLabel("Projektname").press("Control+s");
  await expect(page.locator(".save-state")).toContainText("Projektdatei gespeichert");
  expect(await count()).toBe(1);
  expect(await readName(a)).toBe("Changed");
  await target(null);
  await saveAs();
  await expect(page.getByRole("button", { name: "Speichern", exact: true })).toBeEnabled();
  await page.getByLabel("Projektname").fill("After cancel");
  await save();
  await expect.poll(() => readName(a)).toBe("After cancel");
  expect(await count()).toBe(2);
  await target(b);
  await page.getByLabel("Projektname").press("Control+Shift+s");
  await expect.poll(() => readName(b).catch(() => "")).toBe("After cancel");
  await page.getByLabel("Projektname").fill("Copy");
  await save();
  await expect.poll(() => readName(b)).toBe("Copy");
  expect(await readName(a)).toBe("After cancel");
  expect(await count()).toBe(3);
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("skin-forge-project-v1")).workspace.file.path)).toBe(b);
  await app.close();
  page = await launch();
  await page.getByLabel("Projektname").fill("After restart");
  await save();
  await expect.poll(() => readName(b)).toBe("After restart");
  expect(await count()).toBe(0);
  await app.evaluate((_, file) => { global.__source = file; }, a);
  await page.getByRole("button", { name: "Öffnen", exact: true }).click();
  await expect(page.getByLabel("Projektname")).toHaveValue("After cancel");
  await page.getByLabel("Projektname").fill("Opened A");
  await save();
  await expect.poll(() => readName(a)).toBe("Opened A");
  expect(await count()).toBe(0);
  await page.getByRole("button", { name: "Neu", exact: true }).click();
  await page.getByRole("button", { name: "Speichern und neu", exact: true }).click();
  await expect(page.getByLabel("Projektname")).toHaveValue("Neuer Skin");
  expect(await count()).toBe(0);
  await save();
  await expect(page.getByRole("button", { name: "Speichern", exact: true })).toBeEnabled();
  expect(await count()).toBe(1);
  // Exported PNG import must detach the previous project destination.
  const png = path.join(dir, "skin.png");
  await page.evaluate(async () => {
    const canvas = document.createElement("canvas"); canvas.width = canvas.height = 64;
    canvas.getContext("2d").fillRect(0, 0, 64, 64);
    window.__testPNG = canvas.toDataURL("image/png").split(",")[1];
  });
  await writeFile(png, Buffer.from(await page.evaluate(() => window.__testPNG), "base64"));
  await app.evaluate((_, file) => { global.__source = file; }, b);
  await page.getByRole("button", { name: "Öffnen", exact: true }).click();
  await expect(page.getByLabel("Projektname")).toHaveValue("After restart");
  await app.evaluate((_, file) => { global.__source = file; }, png);
  await page.getByRole("button", { name: "Öffnen", exact: true }).click();
  await expect(page.getByLabel("Projektname")).toHaveValue("skin");
  await save();
  await expect(page.getByRole("button", { name: "Speichern", exact: true })).toBeEnabled();
  expect(await count()).toBe(2);
  expect(await readName(b)).toBe("After restart");
  await page.screenshot({ path: path.join(dir, "project-save.png") });
  console.log("PASS: first save, direct overwrite, dirty state, shortcuts, Save As/cancel, restart, native open, new project, PNG detachment.");
} finally { await app?.close(); }
